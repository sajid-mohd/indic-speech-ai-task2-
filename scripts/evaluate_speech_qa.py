#!/usr/bin/env python3
"""Run end-to-end ASR -> LLM evaluation on a held-out Hindi speech-Q&A set.

The dataset's speech was generated by MMS Hindi TTS. Use it for reproducible
pipeline testing, not as a substitute for real-speaker evaluation. The script
streams examples to avoid downloading the full dataset (which is large and gated).
"""
from __future__ import annotations

import argparse
import io
import sys
import importlib.metadata
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
import soundfile as sf
import torch
from datasets import load_dataset, get_dataset_split_names
from huggingface_hub import HfApi

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from speech_ai.pipeline import SpeechAssistant  # noqa: E402
from speech_ai.metrics import character_error_rate, corpus_error_rates, word_error_rate  # noqa: E402

DATASET_ID = "Pastaaaaa2003/Hindi-speech-instruct"


def decode_audio(audio_obj) -> tuple[np.ndarray, int]:
    """Decode both legacy Datasets audio dictionaries and newer AudioDecoder objects."""
    if isinstance(audio_obj, np.ndarray):
        raise TypeError("Dataset audio is expected to include its sampling rate")
    if isinstance(audio_obj, dict) and audio_obj.get("array") is not None:
        values = np.asarray(audio_obj["array"], dtype=np.float32)
        sr = int(audio_obj.get("sampling_rate", 16_000))
    elif hasattr(audio_obj, "get_all_samples"):
        decoded = audio_obj.get_all_samples()
        values = decoded.data
        if hasattr(values, "cpu"):
            values = values.cpu().numpy()
        values = np.asarray(values, dtype=np.float32)
        sr = int(decoded.sample_rate)
    elif isinstance(audio_obj, dict) and audio_obj.get("bytes"):
        values, sr = sf.read(io.BytesIO(audio_obj["bytes"]), dtype="float32", always_2d=False)
        values = np.asarray(values, dtype=np.float32)
    elif isinstance(audio_obj, dict) and audio_obj.get("path"):
        values, sr = sf.read(audio_obj["path"], dtype="float32", always_2d=False)
        values = np.asarray(values, dtype=np.float32)
    else:
        raise ValueError("Unrecognized audio field; expected array, AudioDecoder, bytes, or path")
    # AudioDecoder returns channel-first data; the legacy path may return samples x channels.
    if values.ndim == 2:
        values = values.mean(axis=0) if hasattr(audio_obj, "get_all_samples") else values.mean(axis=1)
    return values.reshape(-1), int(sr)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n-samples", type=int, default=100)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--split", choices=["train", "validation", "test"], default="validation",
                        help="Split to evaluate. The current dataset card documents train/validation; unavailable splits are rejected at runtime.")
    parser.add_argument("--max-new-tokens", type=int, default=192,
                        help="LLM response token budget; report outputs that hit this cap as a truncation proxy")
    parser.add_argument("--asr-backend", default="whisper", choices=["whisper", "indic-transcribe"],
                        help="ASR backend; Indic-Transcribe requires approved Hugging Face access")
    parser.add_argument("--asr-model-size", default="small", help="Used only when --asr-backend=whisper")
    parser.add_argument("--llm-model", default="Qwen/Qwen2.5-1.5B-Instruct")
    parser.add_argument("--beam-size", type=int, default=5)
    parser.add_argument("--device", default="auto", choices=["auto", "cpu", "cuda"])
    parser.add_argument("--compute-type", default="auto")
    parser.add_argument("--output-dir", default=str(ROOT / "results"))
    return parser.parse_args()


def run(args: argparse.Namespace) -> pd.DataFrame:
    if args.n_samples < 1:
        raise ValueError("--n-samples must be at least 1")
    if args.max_new_tokens < 1:
        raise ValueError("--max-new-tokens must be at least 1")

    print(f"Loading Q&A {args.split} stream. Accept the dataset access conditions on Hugging Face first.")
    available_splits = get_dataset_split_names(DATASET_ID)
    if args.split not in available_splits:
        raise ValueError(
            f"Requested split {args.split!r} does not exist for {DATASET_ID}. "
            f"Available splits: {available_splits}. The current dataset card documents train/validation, not test."
        )

    # Pin the dataset snapshot so a resumed run cannot silently use a newer revision.
    dataset_revision = HfApi().dataset_info(DATASET_ID).sha

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    path = output_dir / "qa_predictions_for_review.csv"
    partial_path = output_dir / "qa_predictions.partial.csv"
    config_path = output_dir / "qa_run_config.json"
    run_config = {
        "dataset": DATASET_ID,
        "dataset_revision": dataset_revision,
        "split": args.split,
        "n_samples": args.n_samples,
        "seed": args.seed,
        "asr_backend": args.asr_backend,
        "asr_model_size": args.asr_model_size,
        "llm_model": args.llm_model,
        "max_new_tokens": args.max_new_tokens,
        "beam_size": args.beam_size,
        "device": args.device,
        "compute_type": args.compute_type,
    }
    if config_path.exists():
        previous = __import__("json").loads(config_path.read_text(encoding="utf-8"))
        if previous != run_config:
            raise RuntimeError(
                f"Output directory run settings differ from existing manifest {config_path}. "
                "Use the same settings to resume, or choose a new --output-dir."
            )
    else:
        if path.exists() or partial_path.exists():
            raise RuntimeError("Existing QA output/checkpoint has no run manifest; use a new --output-dir to avoid mixing runs.")
        config_path.write_text(__import__("json").dumps(run_config, ensure_ascii=False, indent=2), encoding="utf-8")
    if path.exists() and not partial_path.exists():
        raise FileExistsError(
            f"Completed output already exists: {path}. Review it or choose a new --output-dir; it will not be overwritten."
        )

    stream = load_dataset(DATASET_ID, split=args.split, streaming=True, revision=dataset_revision)
    stream = stream.shuffle(seed=args.seed, buffer_size=max(1000, args.n_samples * 3))
    assistant = SpeechAssistant(
        asr_model_size=args.asr_model_size,
        llm_model_id=args.llm_model,
        load_llm=True,
        device=args.device,
        compute_type=args.compute_type,
        max_new_tokens=args.max_new_tokens,
        asr_backend=args.asr_backend,
    )

    rows: list[dict] = []
    completed: set[str] = set()
    if partial_path.exists():
        try:
            partial = pd.read_csv(partial_path, keep_default_na=False)
            rows = partial.to_dict(orient="records")
            completed = set(partial["sample_id"].astype(str))
            print(f"Resuming from checkpoint: {len(completed)} / {args.n_samples} examples already completed")
        except Exception as exc:
            raise RuntimeError(f"Could not read QA checkpoint {partial_path}: {exc}") from exc
    for i, item in enumerate(stream.take(args.n_samples)):
        sample_id = f"sample-{i:04d}"
        if sample_id in completed:
            continue
        audio, sr = decode_audio(item["audio"])
        question = str(item.get("user_text", ""))
        expected_answer = str(item.get("assistant_text", ""))
        result = assistant.process_array(audio, sr, language="hi", beam_size=args.beam_size)
        dataset_id = item.get("id")
        rows.append({
            "sample_id": sample_id,
            "dataset_id": str(dataset_id) if dataset_id is not None else "",
            "language": "hi",
            "asr_backend": args.asr_backend,
            "asr_decoder": result.get("decoder", "model_default"),
            "beam_size_applied": args.beam_size if args.asr_backend == "whisper" else None,
            "fallback_triggered": bool(result.get("fallback_triggered", False)),
            "condition": "tts_clean",
            "question_reference": question,
            "transcript_prediction": result["transcript"],
            "asr_wer": word_error_rate(question, result["transcript"]),
            "asr_cer": character_error_rate(question, result["transcript"]),
            "reference_response": expected_answer,
            "model_response": result["response"],
            "asr_latency_s": result["asr_latency_s"],
            "llm_latency_s": result["llm_latency_s"],
            "pipeline_latency_s": result["pipeline_latency_s"],
            "audio_duration_s": result["audio_duration_s"],
            "asr_rtf": result["asr_rtf"],
            "pipeline_rtf": result["pipeline_rtf"],
            "prompt_tokens": result.get("prompt_tokens", 0),
            "completion_tokens": result.get("completion_tokens", 0),
            "response_token_limit_hit": bool(result.get("completion_tokens", 0) >= args.max_new_tokens),
            # Reviewers fill these fields after examining the generated response.
            "human_correct_0_or_1": "",
            "human_hallucination_0_or_1": "",
            "response_truncated_0_or_1": "",
            "review_notes": "",
        })
        # Atomically persist each completed example so runtime resets can resume.
        checkpoint_df = pd.DataFrame(rows)
        temp_path = partial_path.with_suffix(".tmp.csv")
        checkpoint_df.to_csv(temp_path, index=False, encoding="utf-8-sig")
        temp_path.replace(partial_path)
        completed.add(sample_id)
        if (i + 1) % 10 == 0 or i + 1 == args.n_samples:
            print(f"  processed/checkpointed {i + 1}/{args.n_samples}")

    df = pd.DataFrame(rows).sort_values("sample_id").reset_index(drop=True)
    if len(df) != args.n_samples:
        raise RuntimeError(
            f"Expected {args.n_samples} QA rows after sampling/resume, got {len(df)}. "
            "Check dataset access, split availability, and streaming/checkpoint configuration."
        )
    df.to_csv(path, index=False, encoding="utf-8-sig")
    partial_path.unlink(missing_ok=True)
    corpus_metrics = corpus_error_rates(
        df["question_reference"].tolist(), df["transcript_prediction"].tolist()
    )
    def package_version(name: str) -> str | None:
        try:
            return importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            return None

    summary = {
        "run_timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "settings": vars(args),
        "dataset": DATASET_ID,
        "dataset_revision": dataset_revision,
        "split": args.split,
        "asr_backend": args.asr_backend,
        "asr_decoder": "Whisper beam search" if args.asr_backend == "whisper" else "Indic-Transcribe model-default decoder (beam-size option not applicable)",
        "beam_size_applied": args.beam_size if args.asr_backend == "whisper" else None,
        "asr_model_revision": getattr(assistant, "asr_model_revision", None),
        "llm_model_id": args.llm_model,
        "llm_model_revision": getattr(assistant, "llm_model_revision", None),
        "gpu": torch.cuda.get_device_name(0) if torch.cuda.is_available() else "CPU",
        "torch_version": torch.__version__,
        "package_versions": {
            name: package_version(name)
            for name in ["transformers", "datasets", "faster-whisper", "ctranslate2", "huggingface-hub"]
        },
        "n_samples": int(len(df)),
        "max_new_tokens": args.max_new_tokens,
        "completion_at_token_limit_n": int(df["response_token_limit_hit"].astype(bool).sum()),
        "completion_at_token_limit_rate": float(df["response_token_limit_hit"].astype(bool).mean()),
        "speech_source_note": "Question recordings are generated by MMS Hindi TTS.",
        "corpus_wer": corpus_metrics["wer"],
        "corpus_cer": corpus_metrics["cer"],
        "mean_asr_latency_s": float(df["asr_latency_s"].mean()),
        "mean_llm_latency_s": float(df["llm_latency_s"].mean()),
        "mean_pipeline_latency_s": float(df["pipeline_latency_s"].mean()),
        "median_pipeline_latency_s": float(df["pipeline_latency_s"].median()),
        "mean_asr_rtf": float(df["asr_rtf"].mean()),
        "mean_pipeline_rtf": float(df["pipeline_rtf"].mean()),
        "response_quality_note": "Correctness/hallucination are scored after human review; see the CSV columns and rubric.",
    }
    summary_path = output_dir / "qa_run_summary.json"
    summary_path.write_text(__import__("json").dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {path}")
    print(f"Wrote {summary_path}")
    print("Do not report response correctness/hallucination until the human-review columns are filled.")
    print(f"Question transcript corpus metrics: WER={corpus_metrics['wer']:.4f}, CER={corpus_metrics['cer']:.4f}")
    print(f"Mean pipeline latency: {df['pipeline_latency_s'].mean():.3f} s")
    print(f"Mean pipeline RTF: {df['pipeline_rtf'].mean():.3f}")
    return df


if __name__ == "__main__":
    run(parse_args())
